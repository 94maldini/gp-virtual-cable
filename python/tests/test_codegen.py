from pathlib import Path

from gpcable import codegen
from gpcable.codegen import inf_escape, render_header, render_inx
from gpcable.config import default_config_path, load_config

TEMPLATE = (Path(codegen.__file__).parent / "templates" / "GPVirtualCable.inx.in").read_text(encoding="utf-8")


def test_header_has_all_minipairs():
    h = render_header(load_config(default_config_path()))
    assert "#define GP_CABLE_COUNT 12" in h
    assert "GENERATED by python -m gpcable.codegen" in h
    for cid in ["Mono1", "Mono8", "Stereo1", "Stereo4"]:
        for k in ["WaveRender", "TopoRender", "WaveCapture", "TopoCapture"]:
            assert f'L"{k}{cid}"' in h
    assert h.count("CableRenderWaveDescriptorMono") == 8
    assert h.count("CableCaptureWaveDescriptorStereo") == 4
    assert h.count("ENDPOINT_NO_FLAGS") == 24
    assert "static const ULONG g_GpCableChannels[GP_CABLE_COUNT] = { 1, 1, 1, 1, 1, 1, 1, 1, 2, 2, 2, 2 };" in h
    assert "    11,  // CableIndex" in h


def test_inx_interfaces_and_names():
    inx = render_inx(load_config(default_config_path()), TEMPLATE)
    assert inx.count("AddInterface=%KSCATEGORY_RENDER%") == 12
    assert inx.count("AddInterface=%KSCATEGORY_CAPTURE%") == 12
    assert 'GP_Stereo4_Name="GP Stereo 4"' in inx
    names = [l for l in inx.splitlines()
             if l.startswith("KSNAME_") and l.split("_", 1)[1].startswith(("Wave", "Topo"))]
    assert len(names) == 48
    assert "@@" not in inx


def test_template_placeholders_once():
    for p in ("@@INTERFACE_SECTIONS@@", "@@ADD_INTERFACES@@", "@@STRINGS@@"):
        assert TEMPLATE.count(p) == 1


def test_inf_string_escaping():
    assert inf_escape('50% "Mic"') == '50%% ""Mic""'


def test_cli_writes_both_files(tmp_path, capsys):
    assert codegen.main(["--out-root", str(tmp_path)]) == 0
    h = tmp_path / "driver" / "Source" / "Filters" / "cables_generated.h"
    i = tmp_path / "driver" / "Source" / "Main" / "GPVirtualCable.inx"
    assert "GP_CABLE_COUNT 12" in h.read_text(encoding="utf-8")
    assert "@@" not in i.read_text(encoding="utf-8")
    out = capsys.readouterr().out
    assert str(h) in out and str(i) in out
