# --- Nama endpoint: GUID Name pin bridge + MediaCategories (Task 4 fix round 1) ---------------

import dataclasses
import re
import uuid as _uuid

_GUID_RE = r"[0-9A-F]{8}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{4}-[0-9A-F]{12}"


def _header_guids(h: str) -> dict[str, str]:
    """Nama variabel GUID -> string GUID dari komentar, dan cek initializer cocok dengan string."""
    out = {}
    pat = re.compile(r"static const GUID (GpPinName\w+) =\s*\{ 0x([0-9a-f]{8}), 0x([0-9a-f]{4}), 0x([0-9a-f]{4}),"
                     r" \{ ((?:0x[0-9a-f]{2}, ){7}0x[0-9a-f]{2}) \} \};\s*// \{(" + _GUID_RE + r")\}")
    for m in pat.finditer(h):
        name, d1, d2, d3, d4, text = m.groups()
        tail = "".join(b[2:] for b in d4.split(", "))
        assert _uuid.UUID(d1 + d2 + d3 + tail) == _uuid.UUID(text), name
        out[name] = text
    return out


def test_pin_name_guids_distinct_and_stable():
    cfg = load_config(default_config_path())
    h1 = render_header(cfg)
    h2 = render_header(cfg)
    assert h1 == h2
    g = _header_guids(h1)
    assert len(g) == 13
    assert len(set(g.values())) == 13
    assert "GpPinNameCapture" in g and "GpPinNameMono1" in g and "GpPinNameStereo4" in g


def test_each_endpoint_has_own_topology_descriptor():
    h = render_header(load_config(default_config_path()))
    for cid in ["Mono1", "Mono8", "Stereo1", "Stereo4"]:
        assert f"GP_DEFINE_RENDER_TOPO({cid}, GpPinName{cid})" in h
        assert f"&GpTopoDescriptor{cid}," in h
    assert "GP_DEFINE_CAPTURE_TOPO(Capture, GpPinNameCapture)" in h
    assert "&GpTopoDescriptorCapture," in h
    assert "&SpeakerTopoMiniportFilterDescriptor" not in h
    assert "&MicArray1TopoMiniportFilterDescriptor" not in h


def test_inx_media_categories_for_all_names():
    cfg = load_config(default_config_path())
    h = render_header(cfg)
    inx = render_inx(cfg, TEMPLATE)
    guids = _header_guids(h)
    keys = [f"GP_{c.id}" for c in cfg.cables] + ["GP_Capture"]
    for key in keys:
        line = f"HKR,%MediaCategories%" + chr(92) + f"%{key}_PinName%,Name,,%{key}_Name%"
        assert inx.count(line) == 1, line
    assert len(re.findall(r"^HKR,%MediaCategories%\\", inx, re.M)) == 13
    assert 'MediaCategories="MediaCategories"' in inx
    # GUID di INX sama dengan GUID di header
    for c in cfg.cables:
        assert f'GP_{c.id}_PinName="{{{guids["GpPinName" + c.id]}}}"' in inx
    assert f'GP_Capture_PinName="{{{guids["GpPinNameCapture"]}}}"' in inx
    # MediaCategories hanya di HKR (infverif /w menolak HKLM)
    assert "HKLM," not in inx


def test_inx_media_category_names_escaped():
    cfg = load_config(default_config_path())
    odd = 'Mic "A" 50%'
    c0 = dataclasses.replace(cfg.cables[0], name=odd)
    cfg2 = dataclasses.replace(cfg, cables=(c0,) + cfg.cables[1:], capture_name='Cap "X" %1')
    inx = render_inx(cfg2, TEMPLATE)
    assert f'GP_{c0.id}_Name="{inf_escape(odd)}"' in inx
    assert f'GP_Capture_Name="{inf_escape(cfg2.capture_name)}"' in inx


